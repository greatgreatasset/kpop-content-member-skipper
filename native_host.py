"""Firefox native messaging host: lets the extension's "Filter this video" button
scan a video on this PC (same scan + commit + push as scan.bat, via scan_cli.py).

    install_native_host.bat              register it for Firefox (per user, no admin)
    install_native_host.bat /uninstall   remove the registration

Firefox starts native_host.bat (which runs this file with the project venv) and
talks to it over stdin/stdout: 4-byte little-endian length + UTF-8 JSON.

Extension -> host (one request per connection):
    {"type": "scan", "videoId": "...", "profile": "hearts2hearts", "rescan": false}
    {"type": "attach", "videoId": "..."}       follow a running scan, else "idle"
Host -> extension:
    {"type": "hello", "version": ...}
    {"type": "progress", "videoId", "stage": "starting|download|scan|upload",
     "percent": 0-100, "eta": seconds or null}
    {"type": "done", "videoId", "list": {...skip list...}, "pushed": bool, "note": "..."}
    {"type": "error", "videoId", "message": "..."}
    {"type": "idle", "videoId"}

The scan itself runs in a separate worker process (native_host.py --worker ...)
that writes its state to cache/jobs/<videoId>.json, so it keeps going if Firefox
closes the connection, and a second request for the same video just follows the
running scan instead of starting another one.
"""
import json
import os
import re
import struct
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
JOBS = ROOT / "cache" / "jobs"
HOST_NAME = "kpop_content_member_skipper"
ADDON_ID = "kpop-content-member-skipper@kirk.local"
MANIFEST = ROOT / "native_host.local.json"  # generated by --install, gitignored
LAUNCHER = ROOT / "native_host.bat"
REG_KEY = rf"Software\Mozilla\NativeMessagingHosts\{HOST_NAME}"
VERSION = 1
ID_RE = re.compile(r"^[A-Za-z0-9_-]{11}$")
PROFILE_RE = re.compile(r"^[a-z0-9][a-z0-9_-]*$")
DONE_KEEP = 15 * 60  # report a finished scan to a late "attach" for this long

# overall percent: download 0-15, face scan 15-95, upload 95-100
W_DL, W_SCAN = 15, 80
UPLOAD_ETA = 8


# ------------------------------------------------------------ job files

def job_path(vid):
    return JOBS / f"{vid}.json"


def read_job(vid):
    try:
        return json.loads(job_path(vid).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def write_job(vid, data):
    JOBS.mkdir(parents=True, exist_ok=True)
    tmp = job_path(vid).with_suffix(f".{os.getpid()}.tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
    for _ in range(20):  # the reader may have the file open for a moment
        try:
            os.replace(tmp, job_path(vid))
            return
        except PermissionError:
            time.sleep(0.05)
    tmp.unlink(missing_ok=True)


def pid_alive(pid):
    if not pid:
        return False
    if os.name != "nt":
        try:
            os.kill(pid, 0)
            return True
        except OSError:
            return False
    import ctypes
    k = ctypes.windll.kernel32
    h = k.OpenProcess(0x1000, False, int(pid))  # PROCESS_QUERY_LIMITED_INFORMATION
    if not h:
        return False
    code = ctypes.c_ulong()
    ok = k.GetExitCodeProcess(h, ctypes.byref(code))
    k.CloseHandle(h)
    return bool(ok) and code.value == 259  # STILL_ACTIVE


def running(job):
    return bool(job) and job.get("state") in ("starting", "running") and pid_alive(job.get("pid"))


# ------------------------------------------------------------ worker

class JobProgress:
    """Same hooks as scan_cli.Progress, but written to the job file."""

    def __init__(self, vid, profile):
        self.vid, self.profile = vid, profile
        self.t0 = None
        self.duration = None
        self.last = 0.0
        self.state = dict(state="running", pid=os.getpid(), videoId=vid, profile=profile,
                          stage="download", percent=0, eta=None, started=time.time())
        self.flush(force=True)

    def flush(self, force=False, **kw):
        self.state.update(kw)
        now = time.perf_counter()
        if force or now - self.last >= 0.5:
            self.last = now
            self.state["updated"] = time.time()
            write_job(self.vid, self.state)

    def download_hook(self, d):
        if d.get("status") == "downloading":
            done = d.get("downloaded_bytes") or 0
            total = d.get("total_bytes") or d.get("total_bytes_estimate")
            if total:
                self.flush(stage="download", percent=round(W_DL * min(1, done / total)))

    def cached(self):
        self.flush(force=True, stage="scan", percent=W_DL + W_SCAN, eta=UPLOAD_ETA)

    def detect_start(self, duration):
        self.duration = duration
        self.t0 = time.perf_counter()
        self.flush(force=True, stage="scan", percent=W_DL, eta=None)

    def frame(self, t):
        if not self.duration:
            return
        f = min(1.0, t / self.duration)
        el = time.perf_counter() - self.t0
        eta = round(el * (1 - f) / f + UPLOAD_ETA) if f > 0.03 else None
        self.flush(stage="scan", percent=round(W_DL + W_SCAN * f), eta=eta)


def worker(vid, profile, rescan):
    import scan
    import scan_cli

    prog = JobProgress(vid, profile)
    base = dict(pid=os.getpid(), videoId=vid, profile=profile, started=prog.state["started"])
    p = dict(scan.DEFAULTS)
    try:
        res, _ = scan_cli.scan_video(vid, p, rescan, profile, False, prog)
    except scan.DownloadFailed as e:
        write_job(vid, dict(base, state="error", message=f"Couldn't download the video: {e}",
                            updated=time.time()))
        return 3
    except Exception as e:
        print(f"scan failed: {e!r}", flush=True)
        write_job(vid, dict(base, state="error", message=f"Scan failed: {scan._one_line(e)}",
                            updated=time.time()))
        return 4
    prog.flush(force=True, stage="upload", percent=W_DL + W_SCAN, eta=UPLOAD_ETA)
    no_push = os.environ.get("KMS_NO_PUSH") == "1"
    rc, out = scan_cli.publish(res["videoId"], profile, no_push, capture=True)
    print(out, flush=True)
    if rc == 5:
        note = "Scanned, but the extension's bundled copies could not be refreshed."
    elif rc == 2:
        note = "Scanned and committed, but the upload to GitHub failed (run: git push origin master)."
    elif rc:
        note = "Scanned, but committing the skip list failed."
    else:
        note = "Not uploaded (KMS_NO_PUSH=1)." if no_push else ""
    write_job(vid, dict(base, state="done", list=res, pushed=rc == 0 and not no_push, note=note,
                        stage="done", percent=100, eta=0, updated=time.time()))
    return 0


def start_worker(vid, profile, rescan):
    log = open(JOBS / f"{vid}.log", "w", encoding="utf-8")
    cmd = [sys.executable, str(Path(__file__).resolve()), "--worker", vid, profile]
    if rescan:
        cmd.append("--rescan")
    kw = dict(cwd=ROOT, stdin=subprocess.DEVNULL, stdout=log, stderr=subprocess.STDOUT)
    if os.name == "nt":
        # no console window (ffmpeg/git inherit the hidden one); leave Firefox's job
        # object so the scan survives Firefox closing the connection
        flags = subprocess.CREATE_NO_WINDOW | subprocess.CREATE_NEW_PROCESS_GROUP
        try:
            return subprocess.Popen(cmd, creationflags=flags | subprocess.CREATE_BREAKAWAY_FROM_JOB, **kw)
        except OSError:
            return subprocess.Popen(cmd, creationflags=flags, **kw)
    return subprocess.Popen(cmd, start_new_session=True, **kw)


# ------------------------------------------------------------ messaging

def read_msg(inp):
    raw = inp.read(4)
    if len(raw) < 4:
        return None
    n = struct.unpack("<I", raw)[0]
    return json.loads(inp.read(n).decode("utf-8"))


def send(out, msg):
    data = json.dumps(msg, ensure_ascii=False).encode("utf-8")
    out.write(struct.pack("<I", len(data)) + data)
    out.flush()


def follow(out, vid):
    """Relay a job's progress until it finishes. Returns when done/error."""
    last = None
    while True:
        job = read_job(vid)
        if not job:
            send(out, {"type": "error", "videoId": vid, "message": "The scan did not start."})
            return
        state = job.get("state")
        if state == "done":
            send(out, {"type": "done", "videoId": vid, "list": job.get("list"),
                       "pushed": job.get("pushed", False), "note": job.get("note", "")})
            return
        if state == "error":
            send(out, {"type": "error", "videoId": vid, "message": job.get("message", "Scan failed.")})
            return
        if not pid_alive(job.get("pid")):
            send(out, {"type": "error", "videoId": vid, "message": "The scanner stopped unexpectedly."})
            return
        cur = (job.get("stage"), job.get("percent"), job.get("eta"))
        if cur != last:
            last = cur
            send(out, {"type": "progress", "videoId": vid, "stage": cur[0] or "starting",
                       "percent": cur[1] or 0, "eta": cur[2]})
        time.sleep(0.5)


def handle(out, msg):
    vid = str(msg.get("videoId") or "")
    if not ID_RE.match(vid):
        send(out, {"type": "error", "videoId": vid, "message": "Not a YouTube video ID."})
        return
    job = read_job(vid)
    if msg.get("type") == "attach":
        if running(job) or (job and job.get("state") in ("done", "error")
                            and time.time() - job.get("updated", 0) < DONE_KEEP):
            follow(out, vid)
        else:
            send(out, {"type": "idle", "videoId": vid})
        return
    if msg.get("type") != "scan":
        send(out, {"type": "error", "videoId": vid, "message": "Unknown request."})
        return
    if running(job):  # already scanning this video: just follow it
        follow(out, vid)
        return
    profile = str(msg.get("profile") or "hearts2hearts")
    if not PROFILE_RE.match(profile) or not (ROOT / "profiles" / f"{profile}.json").exists():
        send(out, {"type": "error", "videoId": vid, "message": f"Unknown profile: {profile}"})
        return
    JOBS.mkdir(parents=True, exist_ok=True)
    proc = start_worker(vid, profile, bool(msg.get("rescan")))
    # the worker overwrites this with its own pid (the venv python.exe launcher
    # keeps running until its child exits, so either pid works for liveness)
    write_job(vid, dict(state="starting", pid=proc.pid, videoId=vid, profile=profile,
                        stage="starting", percent=0, eta=None, started=time.time(),
                        updated=time.time()))
    follow(out, vid)


def serve():
    inp, out = sys.stdin.buffer, sys.stdout.buffer
    sys.stdout = sys.stderr  # stray prints must never corrupt the message stream
    os.chdir(ROOT)
    send(out, {"type": "hello", "version": VERSION})
    msg = read_msg(inp)
    if msg is None:
        return 0
    try:
        handle(out, msg)
    except (BrokenPipeError, OSError):
        pass  # Firefox closed the connection; the worker keeps going
    return 0


# ------------------------------------------------------------ install

def install():
    import winreg
    MANIFEST.write_text(json.dumps({
        "name": HOST_NAME,
        "description": "K-pop Content Member Skipper: scan a video on this PC",
        "path": str(LAUNCHER),
        "type": "stdio",
        "allowed_extensions": [ADDON_ID],
    }, indent=2), encoding="utf-8")
    with winreg.CreateKey(winreg.HKEY_CURRENT_USER, REG_KEY) as k:
        winreg.SetValueEx(k, None, 0, winreg.REG_SZ, str(MANIFEST))
    print(f"Installed: Firefox can now start the scanner ({HOST_NAME}).")
    print("Reload the add-on (or restart Firefox) and open a YouTube video:")
    print("the add-on's popup shows a \"Filter this video\" button.")
    return 0


def uninstall():
    import winreg
    try:
        winreg.DeleteKey(winreg.HKEY_CURRENT_USER, REG_KEY)
    except FileNotFoundError:
        pass
    MANIFEST.unlink(missing_ok=True)
    print("Uninstalled: the add-on's \"Filter this video\" button is gone after a reload.")
    return 0


def main():
    args = sys.argv[1:]
    if args[:1] == ["--install"]:
        return install()
    if args[:1] == ["--uninstall"]:
        return uninstall()
    if args[:1] == ["--worker"]:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        os.chdir(ROOT)
        return worker(args[1], args[2], "--rescan" in args)
    return serve()  # started by Firefox (args: manifest path, extension id)


if __name__ == "__main__":
    sys.exit(main())
